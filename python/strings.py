name = "Kumaran"

print("My name:", name)

# Indexing
print("First character:", name[0])

# Slicing
print("First three characters:", name[0:3])

# String methods
print("Uppercase:", name.upper())
print("Lowercase:", name.lower())

# Replace
print("Updated name:", name.replace("K", "S"))

# Length
print("Number of characters:", len(name))
